/// Generate a Rust struct definition for etherparse from a ProtocolDef.
pub fn generate_etherparse(proto: &ProtocolDef) -> String {
    let mappings = type_mapping::load_etherparse_gen_mappings(None)
        .expect("embedded etherparse_gen mappings should always parse");

    let struct_name = canonical_to_pascal(&proto.name);
    let snake = canonical_to_snake(&proto.name);

    let mut out = String::new();

    // Header comment
    out.push_str(&format!(
        "// Auto-generated by proto-audit from IR definition.\n\
         // Protocol: {}\n\
         // Minimum header: {} bytes\n\n",
        proto.name,
        proto.min_header_bits / 8
    ));

    // Derives
    let derives = if mappings.derives.default.is_empty() {
        vec![
            "Debug".to_string(),
            "Clone".to_string(),
            "PartialEq".to_string(),
            "Eq".to_string(),
        ]
    } else {
        mappings.derives.default.clone()
    };
    out.push_str(&format!("#[derive({})]\n", derives.join(", ")));

    // Struct definition
    out.push_str(&format!("pub struct {}Header {{\n", struct_name));

    let mut bitfield_group: Vec<(&str, u32)> = Vec::new();

    for field in &proto.fields {
        // Skip fields that etherparse typically omits
        if mappings.should_skip(&format!("{}Header", struct_name), &field.name) {
            continue;
        }

        // Check for newtype override first, then generic type mapping
        let rust_type = if let Some(nt) = mappings.newtype(&field.name) {
            nt.to_string()
        } else if let Some(rt) = mappings.rust_type(&field.field_type, field.size_bits) {
            rt.to_string()
        } else {
            // Fallback: pick smallest Rust integer that fits
            rust_type_for_bits(field.size_bits)
        };

        // Handle single-bit flags as bool fields
        if field.field_type == FieldType::Flags && field.size_bits == 1 {
            out.push_str(&format!("    pub {}: bool,\n", field.name));
            continue;
        }

        // Handle multi-bit sub-byte fields: group contiguous bitfields
        if field.size_bits < 8 && !is_byte_aligned(field.offset_bits, field.size_bits) {
            bitfield_group.push((&field.name, field.size_bits));
            continue;
        }

        // Flush any pending bitfield group
        flush_bitfield_group(&mut out, &mut bitfield_group);

        // Doc comment with description
        if !field.description.is_empty() {
            out.push_str(&format!("    /// {}\n", field.description));
        }

        out.push_str(&format!("    pub {}: {},\n", field_name_rust(&field.name), rust_type));
    }

    // Flush any remaining bitfield group
    flush_bitfield_group(&mut out, &mut bitfield_group);

    out.push_str("}\n\n");

    // Size assertion
    let min_bytes = proto.min_header_bits / 8;
    out.push_str(&format!(
        "// Wire format: {} bytes minimum\n",
        min_bytes
    ));

    // impl block with from_bytes / to_bytes skeleton
    out.push_str(&format!("impl {}Header {{\n", struct_name));
    out.push_str(&format!("    /// Minimum header size in bytes.\n"));
    out.push_str(&format!("    pub const MIN_LEN: usize = {};\n\n", min_bytes));
    out.push_str(&format!("    /// Read from a byte slice.\n"));
    out.push_str(&format!(
        "    pub fn from_slice(slice: &[u8]) -> Result<{}Header, err::LenError> {{\n",
        struct_name
    ));
    out.push_str("        if slice.len() < Self::MIN_LEN {\n");
    out.push_str("            return Err(err::LenError {\n");
    out.push_str("                required_len: Self::MIN_LEN,\n");
    out.push_str("                len: slice.len(),\n");
    out.push_str("                len_source: err::LenSource::Slice,\n");
    out.push_str(&format!("                layer: err::Layer::{},\n", snake));
    out.push_str("                layer_start_offset: 0,\n");
    out.push_str("            });\n");
    out.push_str("        }\n");
    out.push_str(&format!(
        "        todo!(\"parse {} fields from slice\")\n",
        struct_name
    ));
    out.push_str("    }\n");
    out.push_str("}\n");

    out
}

/// Generate a Python Scapy Packet class definition from a ProtocolDef.
pub fn generate_scapy(proto: &ProtocolDef) -> String {
    let mappings = type_mapping::load_scapy_gen_mappings(None)
        .expect("embedded scapy_gen mappings should always parse");

    let class_name = canonical_to_pascal(&proto.name);

    let mut out = String::new();

    // Header
    out.push_str(&format!(
        "# Auto-generated by proto-audit from IR definition.\n\
         # Protocol: {}\n\n",
        proto.name
    ));

    // Imports
    out.push_str("from scapy.packet import Packet, bind_layers\n");
    out.push_str("from scapy.fields import *\n\n\n");

    // Class definition
    out.push_str(&format!("class {}(Packet):\n", class_name));
    out.push_str(&format!("    name = \"{}\"\n", proto.name));
    out.push_str("    fields_desc = [\n");

    for field in &proto.fields {
        let scapy_name = field
            .source_names
            .get("scapy")
            .map(|s| s.as_str())
            .unwrap_or(&field.name);

        // Determine field class
        let field_class = determine_scapy_class(&field.field_type, field.size_bits,
                                                 scapy_name, &field.endian,
                                                 &field.flag_names, &mappings);

        // Build field constructor
        let field_str = format_scapy_field(&field_class, scapy_name, field.size_bits,
                                           &field.field_type, &field.default_value,
                                           &field.flag_names);

        out.push_str(&format!("        {},\n", field_str));
    }

    out.push_str("    ]\n");

    // bind_layers from dispatch table
    if !proto.dispatch_table.is_empty() {
        out.push_str("\n\n");
        for entry in &proto.dispatch_table {
            if let Some(ref dispatch_field) = proto.dispatch_field {
                let dispatch_name = proto
                    .fields
                    .iter()
                    .find(|f| &f.name == dispatch_field)
                    .and_then(|f| f.source_names.get("scapy"))
                    .map(|s| s.as_str())
                    .unwrap_or(dispatch_field.as_str());

                out.push_str(&format!(
                    "bind_layers({}, {}, {}={})\n",
                    class_name,
                    canonical_to_pascal(&entry.protocol),
                    dispatch_name,
                    format_value(entry.value)
                ));
            }
        }
    }

    out
}

/// Determine the Scapy field class for a given IR field.
fn determine_scapy_class(
    ft: &FieldType,
    bits: u32,
    name: &str,
    endian: &Endian,
    flag_names: &Option<Vec<String>>,
    mappings: &type_mapping::ScapyGenMappings,
) -> String {
    // 1. Name overrides (e.g., src → SourceIPField)
    if let Some(cls) = mappings.name_override(name) {
        return cls.to_string();
    }

    // 2. FlagsField with flag_names
    if *ft == FieldType::Flags && flag_names.is_some() {
        return "FlagsField".to_string();
    }

    // 3. Generic (type, size) mapping
    let base_class = mappings
        .field_class(ft, bits)
        .unwrap_or_else(|| {
            // Fallback for unknown sizes
            if bits <= 8 { "ByteField" }
            else if bits <= 16 { "ShortField" }
            else if bits <= 32 { "IntField" }
            else { "LongField" }
        })
        .to_string();

    // 4. Apply LE prefix if little-endian
    if *endian == Endian::Little {
        if let Some(le) = mappings.le_variant(&base_class) {
            return le.to_string();
        }
    }

    base_class
}

/// Format a Scapy field constructor string.
fn format_scapy_field(
    class: &str,
    name: &str,
    bits: u32,
    ft: &FieldType,
    default: &Option<String>,
    flag_names: &Option<Vec<String>>,
) -> String {
    match class {
        "BitField" => {
            format!(
                "BitField(\"{}\", {}, {})",
                name,
                default.as_deref().unwrap_or("0"),
                bits
            )
        }
        "FlagsField" => {
            if let Some(ref names) = flag_names {
                let names_str: Vec<String> = names.iter().map(|n| format!("\"{}\"", n)).collect();
                format!(
                    "FlagsField(\"{}\", {}, {}, [{}])",
                    name,
                    default.as_deref().unwrap_or("0"),
                    bits,
                    names_str.join(", ")
                )
            } else {
                format!(
                    "FlagsField(\"{}\", {}, {})",
                    name,
                    default.as_deref().unwrap_or("0"),
                    bits
                )
            }
        }
        _ => {
            // Standard field: FieldClass("name", default)
            if let Some(ref d) = default {
                format!("{}(\"{}\", {})", class, name, d)
            } else {
                // Use sensible defaults
                let default_val = match ft {
                    FieldType::Ipv4Addr => "\"0.0.0.0\"",
                    FieldType::Ipv6Addr => "\"::\"",
                    FieldType::MacAddr => "\"00:00:00:00:00:00\"",
                    _ => "0",
                };
                format!("{}(\"{}\", {})", class, name, default_val)
            }
        }
    }
}

/// Format a dispatch value: use hex for values >= 256.
fn format_value(v: u32) -> String {
    if v >= 256 {
        format!("0x{:04x}", v)
    } else {
        v.to_string()
    }
}

/// "IPv4" → "Ipv4", "TCP" → "Tcp", "IEEE802.1Q" → "Ieee8021Q"
fn canonical_to_pascal(name: &str) -> String {
    let mut result = String::new();
    let mut capitalize_next = true;
    for ch in name.chars() {
        if ch == '.' || ch == '-' || ch == '_' || ch == ' ' {
            capitalize_next = true;
            continue;
        }
        if capitalize_next {
            result.push(ch.to_uppercase().next().unwrap_or(ch));
            capitalize_next = false;
        } else {
            result.push(ch.to_lowercase().next().unwrap_or(ch));
        }
    }
    // Special case: keep well-known acronyms
    // Actually, for Scapy we want the original name as class name
    // Return the canonical name directly for Scapy compatibility
    name.replace('.', "").replace('-', "").replace(' ', "")
}

/// Determine smallest Rust integer type for a given bit width.
fn rust_type_for_bits(bits: u32) -> String {
    match bits {
        0..=1 => "bool".to_string(),
        2..=8 => "u8".to_string(),
        9..=16 => "u16".to_string(),
        17..=32 => "u32".to_string(),
        33..=64 => "u64".to_string(),
        _ => "u128".to_string(),
    }
}

/// Convert field name to valid Rust identifier.
fn field_name_rust(name: &str) -> String {
    let name = name
        .to_lowercase()
        .replace('.', "_")
        .replace('-', "_")
        .replace(' ', "_");
    // Avoid Rust keywords
    match name.as_str() {
        "type" => "r#type".to_string(),
        "mod" => "r#mod".to_string(),
        "ref" => "r#ref".to_string(),
        _ => name,
    }
}

/// Check if a field is byte-aligned (both offset and size are multiples of 8).
fn is_byte_aligned(offset_bits: u32, size_bits: u32) -> bool {
    offset_bits % 8 == 0 && size_bits % 8 == 0
}

/// Flush accumulated bitfield entries as a comment + packed field.
fn flush_bitfield_group(out: &mut String, group: &mut Vec<(&str, u32)>) {
    if group.is_empty() {
        return;
    }
    let total_bits: u32 = group.iter().map(|(_, b)| b).sum();
    let rust_type = rust_type_for_bits(total_bits);
    // Emit each sub-field as a doc comment showing bit allocation
    out.push_str("    /// Packed bitfield:\n");
    for (name, bits) in group.iter() {
        out.push_str(&format!("    ///   {} ({} bits)\n", name, bits));
    }
    // Use first field name as the packed field name
    let field_name = group[0].0;
    out.push_str(&format!("    pub {}_raw: {},\n", field_name_rust(field_name), rust_type));
    group.clear();
}

