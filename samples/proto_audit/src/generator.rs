    #[test]
    fn test_generate_scapy_ipv4() {
        let proto = sample_ipv4_rich();
        let output = generate_scapy(&proto);

        assert!(output.contains("class IPv4(Packet)"));
        // BitField for sub-byte
        assert!(output.contains("BitField(\"version\", 4, 4)"));
        // FlagsField with flag names
        assert!(output.contains("FlagsField(\"flags\""));
        assert!(output.contains("\"Reserved\""));
        assert!(output.contains("\"DF\""));
        assert!(output.contains("\"MF\""));
        // IP addresses
        assert!(output.contains("SourceIPField(\"src\""));
        assert!(output.contains("DestIPField(\"dst\""));
        // Enum field
        assert!(output.contains("ByteEnumField(\"proto\""));
    }

