/// Generate a Wireshark Lua dissector for a single protocol definition.
///
/// Produces a self-contained Lua script with Proto, ProtoFields, dissector
/// function, and post-dissector registration.
pub fn generate_wireshark_lua_single(proto: &ProtocolDef) -> String {
    let snake = canonical_to_snake(&proto.name);
    let dissector_name = format!("inet_diag_{}", snake);

    let mut out = String::new();
    out.push_str(&format!(
        "-- Auto-generated by proto-audit from IR definition.\n\
         -- Protocol: {}\n\
         --\n\
         -- Load with: tshark -X lua_script:<this_file> -r capture.pcap -T pdml\n\n",
        proto.name
    ));

    generate_proto_block(&mut out, proto, &dissector_name, &snake);

    out.push('\n');
    out.push_str(&format!(
        "register_postdissector(proto_{})\n",
        snake
    ));

    out
}

/// Generate an aggregate Lua script for multiple inet_diag attribute protocols.
///
/// `protos` is a slice of `(attr_type_id, canonical_name, proto_def)` tuples.
/// The generated script walks the RTAttr chain and dispatches each attribute
/// to the matching per-type dissector.
pub fn generate_wireshark_lua(protos: &[(u16, &str, &ProtocolDef)]) -> String {
    let mut out = String::new();

    out.push_str(
        "-- Auto-generated by proto-audit from IR definitions.\n\
         -- Netlink INET_DIAG attribute dissectors.\n\
         --\n\
         -- Decomposes opaque inet_diag attribute payloads (tcp_info, bbr_info,\n\
         -- meminfo, skmeminfo, vegasinfo, dctcpinfo) into individual named fields.\n\
         --\n\
         -- Load with: tshark -X lua_script:<this_file> -r capture.pcap -T pdml\n\n",
    );

    // Generate Proto + ProtoField declarations for each attribute
    for (_, name, proto) in protos {
        let snake = canonical_to_snake(name);
        let dissector_name = format!("inet_diag_{}", snake);
        generate_proto_block(&mut out, proto, &dissector_name, &snake);
        out.push('\n');
    }

    // Generate the aggregate post-dissector that walks RTAttr chain
    out.push_str(
        "-- ================================================================\n\
         -- Aggregate post-dissector: walks RTAttr chain in netlink-sock_diag\n\
         -- ================================================================\n\n",
    );

    out.push_str("local proto_inet_diag_attrs = Proto(\"inet_diag_attrs\", \"INET_DIAG Attribute Dissectors\")\n\n");

    // Field to detect netlink-sock_diag packets
    out.push_str("local f_netlink_family = Field.new(\"netlink.family\")\n");
    out.push_str("local NETLINK_SOCK_DIAG = 4\n");
    out.push_str("local COOKED_HDR = 16\n");
    out.push_str("local NLMSGHDR = 16\n");
    out.push_str("local INET_DIAG_MSG = 72\n\n");

    out.push_str("function proto_inet_diag_attrs.dissector(buffer, pinfo, tree)\n");
    out.push_str("    local family = f_netlink_family()\n");
    out.push_str("    if not family then return end\n");
    out.push_str("    if family.value ~= NETLINK_SOCK_DIAG then return end\n\n");
    out.push_str("    -- Walk netlink messages in the packet\n");
    out.push_str("    local pkt_offset = COOKED_HDR\n");
    out.push_str("    while pkt_offset + NLMSGHDR <= buffer:len() do\n");
    out.push_str("        local nlmsg_len = buffer(pkt_offset, 4):le_uint()\n");
    out.push_str("        local nlmsg_type = buffer(pkt_offset + 4, 2):le_uint()\n");
    out.push_str("        if nlmsg_len < NLMSGHDR or pkt_offset + nlmsg_len > buffer:len() then break end\n");
    out.push_str("        if nlmsg_type == 3 then break end  -- NLMSG_DONE\n\n");
    out.push_str("        if nlmsg_type == 20 then  -- SOCK_DIAG_BY_FAMILY\n");
    out.push_str("            local attr_offset = pkt_offset + NLMSGHDR + INET_DIAG_MSG\n");
    out.push_str("            local msg_end = pkt_offset + nlmsg_len\n\n");
    out.push_str("            while attr_offset + 4 <= msg_end do\n");
    out.push_str("                local rta_len = buffer(attr_offset, 2):le_uint()\n");
    out.push_str("                local rta_type = buffer(attr_offset + 2, 2):le_uint()\n");
    out.push_str("                if rta_len < 4 then break end\n");
    out.push_str("                local payload_len = rta_len - 4\n");
    out.push_str("                local payload_off = attr_offset + 4\n\n");

    // Dispatch to per-attribute dissectors
    let mut first = true;
    for (attr_type, name, proto) in protos {
        let snake = canonical_to_snake(name);
        let keyword = if first { "if" } else { "elseif" };
        first = false;

        out.push_str(&format!(
            "                {} rta_type == {} then  -- {}\n",
            keyword, attr_type, name
        ));
        out.push_str(&format!(
            "                    local subtree = tree:add(proto_{}, buffer(payload_off, payload_len))\n",
            snake
        ));

        // Add each field
        for field in &proto.fields {
            if field.field_type == FieldType::Pad {
                continue;
            }
            let offset_bytes = field.offset_bits / 8;
            let size_bytes = field.size_bits / 8;
            if size_bytes == 0 {
                continue;
            }
            let add_method = lua_add_method(&field.endian, field.size_bits);
            let var_name = format!("f_{}_{}", snake, canonical_to_snake(&field.name));

            if proto.is_variable_length {
                out.push_str(&format!(
                    "                    if payload_len >= {} then subtree:{}({}, buffer(payload_off + {}, {})) end\n",
                    offset_bytes + size_bytes,
                    add_method,
                    var_name,
                    offset_bytes,
                    size_bytes
                ));
            } else {
                out.push_str(&format!(
                    "                    subtree:{}({}, buffer(payload_off + {}, {}))\n",
                    add_method, var_name, offset_bytes, size_bytes
                ));
            }
        }
    }

    if !protos.is_empty() {
        out.push_str("                end\n");
    }

    out.push_str("\n                -- Advance to next 4-byte aligned attribute\n");
    out.push_str("                attr_offset = attr_offset + math.ceil(rta_len / 4) * 4\n");
    out.push_str("            end\n");
    out.push_str("        end\n\n");
    out.push_str("        -- Advance to next netlink message (4-byte aligned)\n");
    out.push_str("        pkt_offset = pkt_offset + math.ceil(nlmsg_len / 4) * 4\n");
    out.push_str("    end\n");
    out.push_str("end\n\n");
    out.push_str("register_postdissector(proto_inet_diag_attrs)\n");

    out
}

