//! Wireshark Lua post-dissector generator.
//!
//! Generates Lua scripts that decompose opaque netlink inet_diag attribute
//! payloads (tcp_info, bbr_info, meminfo, skmeminfo, etc.) into individually
//! named ProtoFields. When loaded via `tshark -X lua_script:<path>`, each
//! attribute appears as a fully dissected subtree in PDML output.
//!
//! The generated Lua registers as a post-dissector on packets containing
//! the `netlink-sock_diag` protocol, walks the RTAttr TLV chain after the
//! 72-byte inet_diag_msg body, and dispatches to per-attribute dissectors.

use crate::ir::{Endian, FieldType, ProtocolDef};

use super::canonical_to_snake;

// ---------------------------------------------------------------------------
// Attribute type ID → dissector name mapping
// ---------------------------------------------------------------------------

/// Known inet_diag attribute types with their proto-audit canonical names.
const INET_DIAG_ATTRS: &[(u16, &str)] = &[
    (1, "NL_Diag_MemInfo"),
    (2, "NL_Diag_TCPInfo"),
    (3, "NL_Diag_VegasInfo"),
    (7, "NL_Diag_SkMemInfo"),
    (9, "NL_Diag_DCTCPInfo"),
    (16, "NL_Diag_BBRInfo"),
];

// ---------------------------------------------------------------------------
// IR → Lua type mapping
// ---------------------------------------------------------------------------

/// Map an IR FieldType + size to a Lua ProtoField constructor and base.
fn lua_proto_field(ft: &FieldType, size_bits: u32) -> (&'static str, &'static str) {
    match ft {
        FieldType::Ipv4Addr => ("ProtoField.ipv4", ""),
        FieldType::Ipv6Addr => ("ProtoField.ipv6", ""),
        FieldType::MacAddr => ("ProtoField.ether", ""),
        FieldType::Bytes | FieldType::Pad => ("ProtoField.bytes", ""),
        FieldType::Flags => match size_bits {
            0..=8 => ("ProtoField.uint8", ", base.HEX"),
            9..=16 => ("ProtoField.uint16", ", base.HEX"),
            17..=32 => ("ProtoField.uint32", ", base.HEX"),
            _ => ("ProtoField.uint64", ", base.HEX"),
        },
        FieldType::Sint => match size_bits {
            0..=8 => ("ProtoField.int8", ", base.DEC"),
            9..=16 => ("ProtoField.int16", ", base.DEC"),
            17..=32 => ("ProtoField.int32", ", base.DEC"),
            _ => ("ProtoField.int64", ", base.DEC"),
        },
        _ => match size_bits {
            // Uint, Enum, and default
            0..=8 => ("ProtoField.uint8", ", base.DEC"),
            9..=16 => ("ProtoField.uint16", ", base.DEC"),
            17..=32 => ("ProtoField.uint32", ", base.DEC"),
            _ => ("ProtoField.uint64", ", base.DEC"),
        },
    }
}

/// Return the Lua `add` or `add_le` method based on endianness.
fn lua_add_method(endian: &Endian, size_bits: u32) -> &'static str {
    if size_bits <= 8 {
        return "add"; // single-byte: endianness doesn't apply
    }
    match endian {
        Endian::Big => "add",
        _ => "add_le", // Little and Na default to little-endian for netlink
    }
}

