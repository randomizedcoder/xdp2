/// Generate the Proto + ProtoField declarations block for one protocol.
fn generate_proto_block(
    out: &mut String,
    proto: &ProtocolDef,
    dissector_name: &str,
    snake: &str,
) {
    // Proto declaration
    out.push_str(&format!(
        "local proto_{} = Proto(\"{}\", \"{}\")\n\n",
        snake, dissector_name, proto.name
    ));

    // ProtoField declarations
    let mut field_vars = Vec::new();
    for field in &proto.fields {
        if field.field_type == FieldType::Pad {
            continue;
        }
        let field_snake = canonical_to_snake(&field.name);
        let var_name = format!("f_{}_{}", snake, field_snake);
        let filter_name = format!("{}.{}", dissector_name, field_snake);
        let (proto_field, base) = lua_proto_field(&field.field_type, field.size_bits);

        let description = if field.description.is_empty() {
            field.name.clone()
        } else {
            field.description.clone()
        };

        if base.is_empty() {
            out.push_str(&format!(
                "local {} = {}(\"{}\", \"{}\")\n",
                var_name, proto_field, filter_name, description
            ));
        } else {
            out.push_str(&format!(
                "local {} = {}(\"{}\", \"{}\"{})\n",
                var_name, proto_field, filter_name, description, base
            ));
        }
        field_vars.push(var_name);
    }

    // fields table
    if !field_vars.is_empty() {
        out.push_str(&format!(
            "proto_{}.fields = {{ {} }}\n",
            snake,
            field_vars.join(", ")
        ));
    }

    out.push('\n');

    // Single-protocol dissector function (for generate_wireshark_lua_single)
    out.push_str(&format!(
        "function proto_{}.dissector(buffer, pinfo, tree)\n",
        snake
    ));
    out.push_str("    local offset = 0\n");
    out.push_str("    local subtree = tree:add(proto_");
    out.push_str(snake);
    out.push_str(", buffer())\n");

    for field in &proto.fields {
        if field.field_type == FieldType::Pad {
            continue;
        }
        let offset_bytes = field.offset_bits / 8;
        let size_bytes = field.size_bits / 8;
        if size_bytes == 0 {
            continue;
        }
        let field_snake = canonical_to_snake(&field.name);
        let var_name = format!("f_{}_{}", snake, field_snake);
        let add_method = lua_add_method(&field.endian, field.size_bits);

        if proto.is_variable_length {
            out.push_str(&format!(
                "    if buffer:len() >= {} then subtree:{}({}, buffer({}, {})) end\n",
                offset_bytes + size_bytes,
                add_method,
                var_name,
                offset_bytes,
                size_bytes
            ));
        } else {
            out.push_str(&format!(
                "    subtree:{}({}, buffer({}, {}))\n",
                add_method, var_name, offset_bytes, size_bytes
            ));
        }
    }

    out.push_str("end\n");
}

