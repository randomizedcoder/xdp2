#[cfg(test)]
mod tests {
    use super::*;
    use crate::ir::{Endian, FieldDef, FieldType, ProtocolDef};

    fn sample_bbrinfo() -> ProtocolDef {
        ProtocolDef::new("NL_Diag_BBRInfo", 160).with_fields(vec![
            FieldDef::new("bbr_bw_lo", 0, 32, FieldType::Uint)
                .with_endian(Endian::Little)
                .with_description("Bandwidth low 32 bits"),
            FieldDef::new("bbr_bw_hi", 32, 32, FieldType::Uint)
                .with_endian(Endian::Little)
                .with_description("Bandwidth high 32 bits"),
            FieldDef::new("bbr_min_rtt", 64, 32, FieldType::Uint)
                .with_endian(Endian::Little)
                .with_description("Minimum RTT (us)"),
            FieldDef::new("bbr_pacing_gain", 96, 32, FieldType::Uint)
                .with_endian(Endian::Little)
                .with_description("Pacing gain"),
            FieldDef::new("bbr_cwnd_gain", 128, 32, FieldType::Uint)
                .with_endian(Endian::Little)
                .with_description("Cwnd gain"),
        ])
    }

    fn sample_tcpinfo_short() -> ProtocolDef {
        ProtocolDef::new("NL_Diag_TCPInfo", 1984)
            .with_variable_length()
            .with_fields(vec![
                FieldDef::new("state", 0, 8, FieldType::Uint)
                    .with_endian(Endian::Little)
                    .with_description("TCP state"),
                FieldDef::new("rto", 64, 32, FieldType::Uint)
                    .with_endian(Endian::Little)
                    .with_description("Retransmit timeout"),
                FieldDef::new("snd_mss", 128, 32, FieldType::Uint)
                    .with_endian(Endian::Little)
                    .with_description("Send MSS"),
            ])
    }

    fn sample_sockid() -> ProtocolDef {
        ProtocolDef::new("NL_Diag_SockID", 384).with_fields(vec![
            FieldDef::new("sport", 0, 16, FieldType::Uint)
                .with_endian(Endian::Big)
                .with_description("Source port"),
            FieldDef::new("dport", 16, 16, FieldType::Uint)
                .with_endian(Endian::Big)
                .with_description("Destination port"),
            FieldDef::new("src_ip", 32, 128, FieldType::Bytes)
                .with_description("Source IP"),
        ])
    }

    #[test]
    fn test_generate_bbrinfo_lua() {
        let proto = sample_bbrinfo();
        let output = generate_wireshark_lua_single(&proto);

        // Proto declaration
        assert!(output.contains("Proto(\"inet_diag_nl_diag_bbrinfo\""));
        // ProtoField declarations with correct types
        assert!(output.contains("ProtoField.uint32(\"inet_diag_nl_diag_bbrinfo.bbr_bw_lo\""));
        assert!(output.contains("ProtoField.uint32(\"inet_diag_nl_diag_bbrinfo.bbr_min_rtt\""));
        // 5 fields in fields table
        assert!(output.contains("proto_nl_diag_bbrinfo.fields = {"));
        // Dissector uses add_le for little-endian u32
        assert!(output.contains("add_le(f_nl_diag_bbrinfo_bbr_bw_lo, buffer(0, 4))"));
        assert!(output.contains("add_le(f_nl_diag_bbrinfo_bbr_cwnd_gain, buffer(16, 4))"));
        // Post-dissector registration
        assert!(output.contains("register_postdissector(proto_nl_diag_bbrinfo)"));
    }

    #[test]
    fn test_generate_tcpinfo_variable_guards() {
        let proto = sample_tcpinfo_short();
        let output = generate_wireshark_lua_single(&proto);

        // Variable-length protocol should have buffer length guards
        assert!(output.contains("if buffer:len() >= 1 then"));   // state at offset 0, size 1
        assert!(output.contains("if buffer:len() >= 12 then"));  // rto at offset 8, size 4
        assert!(output.contains("if buffer:len() >= 20 then"));  // snd_mss at offset 16, size 4
    }

    #[test]
    fn test_field_type_mapping() {
        assert_eq!(lua_proto_field(&FieldType::Uint, 8), ("ProtoField.uint8", ", base.DEC"));
        assert_eq!(lua_proto_field(&FieldType::Uint, 16), ("ProtoField.uint16", ", base.DEC"));
        assert_eq!(lua_proto_field(&FieldType::Uint, 32), ("ProtoField.uint32", ", base.DEC"));
        assert_eq!(lua_proto_field(&FieldType::Uint, 64), ("ProtoField.uint64", ", base.DEC"));
        assert_eq!(lua_proto_field(&FieldType::Sint, 32), ("ProtoField.int32", ", base.DEC"));
        assert_eq!(lua_proto_field(&FieldType::Flags, 8), ("ProtoField.uint8", ", base.HEX"));
        assert_eq!(lua_proto_field(&FieldType::Ipv4Addr, 32), ("ProtoField.ipv4", ""));
        assert_eq!(lua_proto_field(&FieldType::Ipv6Addr, 128), ("ProtoField.ipv6", ""));
        assert_eq!(lua_proto_field(&FieldType::Bytes, 64), ("ProtoField.bytes", ""));
    }

    #[test]
    fn test_endian_handling() {
        let proto = sample_sockid();
        let output = generate_wireshark_lua_single(&proto);

        // Big-endian ports should use add() not add_le()
        assert!(output.contains("subtree:add(f_nl_diag_sockid_sport, buffer(0, 2))"));
        assert!(output.contains("subtree:add(f_nl_diag_sockid_dport, buffer(2, 2))"));
    }

    #[test]
    fn test_aggregate_lua() {
        let bbr = sample_bbrinfo();
        let protos: Vec<(u16, &str, &ProtocolDef)> = vec![
            (16, "NL_Diag_BBRInfo", &bbr),
        ];
        let output = generate_wireshark_lua(&protos);

        // Should have aggregate post-dissector
        assert!(output.contains("proto_inet_diag_attrs"));
        assert!(output.contains("register_postdissector(proto_inet_diag_attrs)"));
        // Should dispatch on attribute type
        assert!(output.contains("if rta_type == 16 then"));
        // Should reference the BBRInfo proto
        assert!(output.contains("tree:add(proto_nl_diag_bbrinfo"));
    }
}
